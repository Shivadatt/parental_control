import fs from 'node:fs';
import path from 'node:path';
import { createClient } from '@supabase/supabase-js';
const ROOT = path.resolve(import.meta.dirname, '../..');
const readEnv = (f) => { const o={}; for (const l of fs.readFileSync(path.join(ROOT,f),'utf8').split(/\r?\n/)) { const i=l.indexOf('='); if(i>0)o[l.slice(0,i).trim()]=l.slice(i+1).trim(); } return o; };
const cfg = readEnv('.tools/live_config.env'); const qa = readEnv('.tools/qa_accounts.env');
const URL = cfg.SUPABASE_URL, KEY = cfg.SUPABASE_ANON_KEY, FAM='4c4dd6fe-e727-4f66-bfba-7edd801114a8';
const c = createClient(URL, KEY, { auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false} });
const { data, error } = await c.auth.signInWithPassword({ email: qa.PARENT_B_USER, password: qa.PARENT_B_PASS });
if (error) throw new Error(error.message);
const res = await fetch(`${URL}/functions/v1/pairing`, { method:'POST', headers:{'Content-Type':'application/json',apikey:KEY,Authorization:`Bearer ${data.session.access_token}`}, body: JSON.stringify({action:'unlink', family_id:FAM, child_user_id: qa.CHILD_C_ID}) });
console.log('unlink', res.status, (await res.text()).slice(0,200));
const m = await c.from('family_members').select('status').eq('family_id', FAM).eq('user_id', qa.CHILD_C_ID).maybeSingle();
console.log('membership', m.data?.status ?? m.error?.message);
const d = await c.from('devices').select('id,status').eq('family_id', FAM).order('created_at',{ascending:false}).limit(3);
console.log('devices', JSON.stringify(d.data ?? d.error?.message));
